#!/usr/bin/env bash
# Regenerates frontend/nginx/snippets/cloudflare-realip.conf from Cloudflare's published ranges.
set -euo pipefail
out="$(cd "$(dirname "$0")/../.." && pwd)/frontend/nginx/snippets/cloudflare-realip.conf"

v4=$(curl --fail --silent --show-error https://www.cloudflare.com/ips-v4)
v6=$(curl --fail --silent --show-error https://www.cloudflare.com/ips-v6)
[ -n "$v4" ] || { echo "ips-v4 download was empty" >&2; exit 1; }
[ -n "$v6" ] || { echo "ips-v6 download was empty" >&2; exit 1; }

tmp=$(mktemp)
{
  echo "# Generated by deploy/scripts/update-cloudflare-ips.sh. Do not edit by hand."
  printf '%s\n%s\n' "$v4" "$v6" | sed '/^[[:space:]]*$/d; s/^\(.*\)$/set_real_ip_from \1;/'
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"
chmod 644 "$tmp"
mv "$tmp" "$out"
echo "Updated $out"
